// `Query.where` takes a Function0, not a lambda with a builder as its receiver, so the comparison
// operators have to be in scope by import. In 1.4.0 they are top-level functions: the
// `SqlExpressionBuilder` object every tutorial still imports from is deprecated, and with warnings
// as errors that idiom does not compile.
import org.jetbrains.exposed.v1.core.eq
import org.jetbrains.exposed.v1.jdbc.Database
import org.jetbrains.exposed.v1.jdbc.insert
import org.jetbrains.exposed.v1.jdbc.selectAll
